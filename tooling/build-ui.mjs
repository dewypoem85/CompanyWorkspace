export function build(check = false) {
  for (const [file,body] of outputs()) {
    const path=resolve(root,file);
    if (check) {
      const matches=existsSync(path)&&(Buffer.isBuffer(body)?readFileSync(path).equals(body):read(file)===body);
      if (!matches) throw Error(`Generated asset differs: ${file}. Run npm run build:ui; never edit outputs directly.`);
    } else { mkdirSync(dirname(path),{recursive:true}); writeFileSync(path,body); }
  }
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) { build(process.argv.includes('--check')); console.log('Shared UI assets verified/generated.'); }
