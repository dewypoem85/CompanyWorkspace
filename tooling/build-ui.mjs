import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root,path),'utf8').replaceAll('\r\n','\n');
export function* walk(directory,base=root) {
  for (const item of readdirSync(resolve(base,directory), {withFileTypes:true})) {
    if (['node_modules','bin','obj','.git','dist','data','wwwroot'].includes(item.name)) continue;
    const path = directory+'/'+item.name;
    if (item.isDirectory()) yield* walk(path,base); else yield path;
  }
}
export function validateAccountFields(fields) {
  const keys = new Set();
  for (const field of fields) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(field.key) || keys.has(field.key)) throw Error('Invalid/duplicate account field key');
    keys.add(field.key);
    if (!['string','bool','long?','DateOnly?','long[]','string[]'].includes(field.type) || !field.label?.trim()) throw Error('Invalid account field type/label');
    if (!['identity','access'].includes(field.section) || !['summary','detail','permissions'].includes(field.placement)) throw Error('Invalid account field layout');
    if (field.maxLength !== undefined && (!Number.isSafeInteger(field.maxLength) || field.maxLength < 1)) throw Error('Invalid account field length');
    if (field.default !== undefined && !((field.type === 'string' && typeof field.default === 'string') || (field.type === 'bool' && typeof field.default === 'boolean'))) throw Error('Invalid account field default');
  }
}
