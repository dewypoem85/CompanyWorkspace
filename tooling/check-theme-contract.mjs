const slash=value=>value.replaceAll('\\','/');
const mask=value=>value.replace(/[^\r\n]/g,' ');

// Preserve offsets for diagnostics. Quoted URLs are not comments; documentation/comments are not token usage.
export function withoutComments(source,{css=false,markup=false}={}) {
  let result='',i=0;
  while(i<source.length) {
    const c=source[i],pair=source.slice(i,i+2);
    if(c==='"'||c==="'"||!css&&c==='`') {
      const start=i++,quote=c;
      while(i<source.length){if(source[i]==='\\'){i+=2;continue;}if(source[i++]===quote)break;}
      result+=source.slice(start,i);continue;
    }
    let end;
    if(pair==='/*')end=source.indexOf('*/',i+2)+2;
    else if(!css&&pair==='//') {end=source.indexOf('\n',i+2);if(end<0)end=source.length;}
    else if(markup&&source.startsWith('<!--',i))end=source.indexOf('-->',i+4)+3;
    else if(markup&&pair==='@*')end=source.indexOf('*@',i+2)+2;
    if(end!==undefined){if(end<=i+2)end=source.length;result+=mask(source.slice(i,end));i=end;continue;}
    result+=c;i++;
  }
  return result;
}
const location=(source,index)=>source.slice(0,index).split('\n').length;

export function themeDefinition(source) {
  const body=withoutComments(source,{css:true}),errors=[];
  const light=[...body.matchAll(/:root\s*\{([^{}]*)\}/g)];
  const dark=[...body.matchAll(/html\[data-theme=["']dark["']\]\s*\{([^{}]*)\}/g)];
  if(light.length!==1||dark.length!==1)return {names:new Set(),errors:['Theme owner requires exactly one flat :root and html[data-theme="dark"] token block.']};
  const declarations=block=>[...block.matchAll(/(--cw-[\w-]+)\s*:\s*([^;{}]+)(?:;|$)/g)];
  const a=declarations(light[0][1]),b=declarations(dark[0][1]),names=new Set(a.map(x=>x[1])),darkNames=new Set(b.map(x=>x[1]));
  if(a.length!==names.size||b.length!==darkNames.size)errors.push('Theme token declarations cannot be duplicated in one mode.');
  for(const name of layoutTokens)if(!names.has(name))errors.push('Missing shared layout token: '+name);
  for(const name of names)if(!invariantTokens.has(name)&&!darkNames.has(name))errors.push('Missing dark theme value: '+name);
  for(const name of darkNames)if(!names.has(name)||invariantTokens.has(name))errors.push('Dark theme cannot introduce tokens or override shared invariants: '+name);
  const outside=body.replace(light[0][0],mask(light[0][0])).replace(dark[0][0],mask(dark[0][0]));
  if(/--cw-[\w-]+\s*:|@property\s+--cw-/.test(outside))errors.push('Shared token definitions must stay in their two canonical mode blocks.');
  return {names,errors};
}

export function checkThemeSource(path,source,definition) {
  if(path===generatedCss)return []; // Generated bytes are checked separately.
  const css=/\.(?:css|scss|sass|less)$/.test(path),markup=/\.(?:html|cshtml|svg)$/.test(path);
  const body=withoutComments(source,{css,markup}),errors=[];
  if(source.includes('--cw-')) {
    for(const match of body.matchAll(/--cw-[A-Za-z0-9_-]*/g)) {
      if(!definition.names.has(match[0])||body.slice(match.index+match[0].length).startsWith('${'))
        errors.push(`${path}:${location(source,match.index)}: undefined or computed shared token ${match[0]}; use a token from ${tokenOwner}.`);
    }
  }
  if(path!==tokenOwner) {
    const writes=[...body.matchAll(/(?:["'`]?(--cw-[\w-]+)["'`]?\s*:|\.setProperty\s*\(\s*["'`](--cw-[\w-]+)["'`]|@property\s+(--cw-[\w-]+))/g)];
    for(const match of writes)errors.push(`${path}:${location(source,match.index)}: ${(match[1]||match[2]||match[3])} is owned by the shared theme; do not override it in page CSS or script.`);
    if(css) {
      for(const match of body.matchAll(/(?:html\s*)?\[data-theme\s*=\s*["']?(?:dark|light)["']?\]|\.theme-(?:dark|light)\b|prefers-color-scheme\s*:/gi))
        errors.push(`${path}:${location(source,match.index)}: application theme-mode CSS is forbidden; map components to shared tokens in ${tokenOwner}.`);
      for(const match of body.matchAll(/(--[\w-]+)\s*:\s*([^;{}]+)(?:;|(?=\}))/g)) {
        if(legacyPaletteAliases.has(match[1])&&!/var\(\s*--cw-[\w-]+\s*(?:,|\))/.test(match[2]))
          errors.push(`${path}:${location(source,match.index)}: ${match[1]} is a palette alias and must map to a shared --cw-* token.`);
      }
    }
  }
  return errors;
}

export function collectThemeSources(base,catalog) {
  const files=new Set(),roots=['packages/workspace-ui/src','packages/workspace-ui/react'];
  if(!Array.isArray(catalog.services)||!catalog.services.length)throw Error('UI source inventory requires registered services.');
  for(const service of catalog.services) {
    if(!/^[a-z][a-z0-9-]*$/.test(service.app))throw Error('Invalid UI application path.');
    const app='apps/'+service.app;
    if(service.adapter==='razor')roots.push(app+'/Pages',app+'/wwwroot');
    else if(service.adapter==='react'){
      if(!/^[a-z][a-z0-9/-]*$/.test(service.client)||service.client.includes('..'))throw Error('Invalid UI client path.');
      roots.push(app+'/'+service.client);
      const document=app+'/'+(service.document||service.client+'/index.html');
      if(slash(relative(resolve(base,app),resolve(base,document))).startsWith('../'))throw Error('UI document must stay in its application.');
      if(!existsSync(resolve(base,document)))throw Error('Missing UI document: '+document);files.add(document);
    } else if(['static','static-spa'].includes(service.adapter))roots.push(app+'/public');
    else throw Error('Register a theme inventory boundary for adapter '+service.adapter);
  }
  const visit=directory=>{
    if(vendorRoots.includes(directory))return;
    for(const item of readdirSync(resolve(base,directory),{withFileTypes:true})) {
      if(['node_modules','.git','bin','obj','dist'].includes(item.name))continue;
      const path=directory+'/'+item.name;
      if(item.isSymbolicLink())throw Error('UI source inventory does not follow symbolic links: '+path);
      if(item.isDirectory())visit(path);else if(extensions.has(extname(path)))files.add(path);
    }
  };
  for(const directory of new Set(roots))visit(directory);
  return [...files].sort().filter(path=>path!==generatedCss);
}

export function checkThemes(base=root) {
  const definition=themeDefinition(readFileSync(resolve(base,tokenOwner),'utf8'));
  const files=collectThemeSources(base,JSON.parse(readFileSync(resolve(base,'packages/contracts/services.json'),'utf8')));
  const errors=[...definition.errors];
  for(const path of files)errors.push(...checkThemeSource(path,readFileSync(resolve(base,path),'utf8'),definition));
  if(errors.length)throw Error(errors.join('\n'));
  return {files:files.length,tokens:definition.names.size};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  try{const result=checkThemes();console.log(`Shared theme contract: ${result.tokens} tokens, ${result.files} UI sources checked.`);}
  catch(error){console.error(error.message);process.exitCode=1;}
}
