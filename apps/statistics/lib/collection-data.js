const BY_ID = new Map(COLLECTIONS.map(item => [item.id, item]));

export function getCollectionMeta(id) {
  return BY_ID.get(Number(id)) || null;
}

export function getCollectionSynergies(ids) {
  return ids.map(getCollectionMeta).filter(item => item && /시너지/.test(item.effect));
}
